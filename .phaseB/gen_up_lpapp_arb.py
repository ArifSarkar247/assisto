for k, (e, b) in K.items():
    assert sorted(set(ph(e))) == sorted(set(ph(b))), k
    en[k] = e
    p = ph(e)
    meta = {"description": "lpapp: Language Partner V2"}
    if p:
        meta["placeholders"] = {x: {"type": "String"} for x in dict.fromkeys(p)}
    en["@" + k] = meta
    bn[k] = b
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "up_lpapp_arb.json")
json.dump({"en": en, "bn": bn}, open(out, "w"), ensure_ascii=False, indent=1)
