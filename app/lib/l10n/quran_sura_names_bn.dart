/// Bangla name of sura [i] (1..114), or '' when out of range.
String suraNameBn(int i) => i >= 1 && i <= kSuraNamesBn.length ? kSuraNamesBn[i - 1] : '';

/// Bangla digits -> ASCII ("২:২৫৫" -> "2:255"); other characters kept.
String asciiDigits(String s) {
  final b = StringBuffer();
  for (final c in s.runes) {
    if (c >= 0x09E6 && c <= 0x09EF) {
      b.writeCharCode(0x30 + c - 0x09E6);
    } else {
      b.writeCharCode(c);
    }
  }
  return b.toString();
}

/// For name search: no hyphen, space or zero-width marks.
String bnNameKey(String s) => s.replaceAll(RegExp('[\\s\\-‌‍]'), '');
