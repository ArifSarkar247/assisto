class Tr:
    """Translator bound to one language."""

    def __init__(self, lang: str = "bn"):
        self.lang = lang if lang in STRINGS else "bn"

    def __call__(self, key: str, **kw):
        val = STRINGS[self.lang].get(key)
        if val is None:
            val = STRINGS["en"].get(key, key)
        return val.format(**kw) if (kw and isinstance(val, str)) else val
