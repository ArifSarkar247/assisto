def add(lang, topic, prompt, summary, points, nxt, *, must=None, pro=None, photo=None,
        fault=None, min_chars=None, cat=None):
    """One case + its recorded fake answer. `lang` bn | en | rom."""
    ans_lang = "en" if lang == "en" else "bn"
    if topic == "legal" and not any(w in " ".join(points + [nxt]) for w in ("আইনজীবী", "lawyer")):
        # a best legal answer in general terms always names the safe next door
        points = points + ["নিজের পরিস্থিতির জন্য একজন আইনজীবীর পরামর্শ নিন।" if ans_lang == "bn"
                           else "For your exact situation, talk to a lawyer."]
    n = sum(1 for c in C if c["cat"] == (cat or lang)) + 1
    cid = "aq-%s-%02d" % (cat or lang, n)
    e = {"answer_lang": ans_lang, "min_chars": min_chars or (140 if photo else 250)}
    if must:
        e["must_any"] = must
    if pro:
        e["pro_line"] = pro
    C.append({"id": cid, "cat": cat or lang, "topic": topic, "prompt": prompt,
              "history": PHOTOS[photo] if photo else [], "expect": e,
              "rubric": {"bd": topic in ("price", "mfs", "legal", "business")
                         or photo in ("bill", "sms", "crop", "nid", "receipt", "en_bill"),
                         "steps": True, "summary": True, "next_step": True},
              "points": points + ([nxt] if nxt else [])})
    nums = [(str(i + 1).translate(BN_D) if ans_lang == "bn" else str(i + 1)) + ". " + p
            for i, p in enumerate(points)]
    nx = ("পরের ধাপ: " if ans_lang == "bn" else "Next step: ") + nxt
    head = "**%s**" % HEAD[ans_lang][topic]
    rec = {"id": cid}
    if fault == "cut":
        k = max(1, len(nums) - 2)
        words = nums[k].split(" ")
        partial = " ".join(words[:max(2, len(words) // 2)])
        partial = partial[:-2] if len(partial) > 6 else partial   # mid-word
        rec["text"] = "\n".join([summary, "", head] + nums[:k] + [partial])
        rec["truncated"] = True
        rec["cont"] = "\n".join(nums[k:] + ["", nx])
    elif fault == "table":
        rows = ["| বিষয় | তথ্য |" if ans_lang == "bn" else "| Item | Detail |", "|---|---|"]
        rows += ["| %s | %s |" % (str(i + 1).translate(BN_D) if ans_lang == "bn" else i + 1, p)
                 for i, p in enumerate(points)]
        rec["text"] = "\n".join([summary, "", head] + rows + ["", nx])
    else:
        rec["text"] = "\n".join([summary, "", head] + nums + ["", nx])
        if fault == "ascii":
            rec["text"] = rec["text"].translate(ASCII_D)
    R.append(rec)


